import * as http from 'http';
import * as os from 'os';
import * as path from 'path';
import express from 'express';
import WebSocket, { WebSocketServer } from 'ws';
import { v4 as uuidv4 } from 'uuid';
import { AudioStreamApp } from '../app';
import { SignalingMessage, RoomInfo, ReceiverInfo } from '../shared/protocol';

interface LocalReceiver {
  receiverId: string;
  joinToken: string;
  clientId: string;
  nickname: string;
  ws: WebSocket;
}

export class LocalSignalingServer {
  private app: AudioStreamApp;
  private httpServer: http.Server | null = null;
  private wss: WebSocketServer | null = null;
  private appExpress: express.Application;
  private port: number = 0;
  private room: RoomInfo | null = null;
  private receivers: Map<string, LocalReceiver> = new Map();
  private senderWs: WebSocket | null = null;
  private senderHandlers: Set<(msg: SignalingMessage) => void> = new Set();
  private localIp: string = '';

  constructor(app: AudioStreamApp) {
    this.app = app;
    this.appExpress = express();
    // Serve /receiver as receiver.html (no .html in QR URL looks cleaner)
    this.appExpress.get('/receiver', (_req, res) => {
      res.sendFile(path.join(__dirname, '../../../public/receiver.html'));
    });
    this.appExpress.use(express.static(path.join(__dirname, '../../../public')));
  }

  async start(preferredPort: number): Promise<number> {
    this.localIp = this.getLocalIp();
    this.port = await this.listen(preferredPort);
    this.setupWebSocket();
    return this.port;
  }

  stop(): void {
    this.wss?.close();
    this.httpServer?.close();
    this.receivers.clear();
    this.senderWs = null;
  }

  getLocalIp(): string {
    return this.localIp || this.getLocalIpInternal();
  }

  getPort(): number {
    return this.port;
  }

  getAllInterfaces(): Array<{ name: string; address: string }> {
    const result = this.collectCandidates();
    return result.map(c => ({ name: c.name, address: c.address }));
  }

  private collectCandidates(): Array<{ address: string; family: string; internal: boolean; name: string }> {
    const interfaces = os.networkInterfaces();
    const candidates: Array<{ address: string; family: string; internal: boolean; name: string }> = [];
    for (const name of Object.keys(interfaces)) {
      const iface = interfaces[name];
      if (!iface) continue;
      for (const alias of iface) {
        if (alias.family === 'IPv4' && !alias.internal) {
          candidates.push({ ...alias, name });
        }
      }
    }
    // Priority: physical > virtual; 192.168 > 10 > 172 > other
    const isVirtual = (c: typeof candidates[0]): boolean => {
      const n = c.name.toLowerCase();
      return n.includes('vether') || n.includes('wsl') || n.includes('docker') ||
             n.includes('vpn') || n.includes('oray') || n.includes('zero') ||
             n.includes('hyper-v') || n.includes('m78');
    };
    const priority = (c: typeof candidates[0]): number => {
      const parts = c.address.split('.').map(Number);
      let p = 0;
      if (isVirtual(c)) p += 100;
      if (parts[0] === 192 && parts[1] === 168) p += 1;
      else if (parts[0] === 10) p += 2;
      else if (parts[0] === 172 && parts[1] >= 16 && parts[1] <= 31) p += 3;
      else p += 99;
      return p;
    };
    candidates.sort((a, b) => priority(a) - priority(b));
    return candidates;
  }

  setLanIp(ip: string): void {
    this.localIp = ip;
  }

  broadcastToSenderClients(msg: SignalingMessage): void {
    // Handle server-side messages locally (main process is the sender in Electron)
    if (msg.type === 'create') {
      this.room = {
        code: this.generateRoomCode(),
        senderToken: uuidv4().replace(/-/g, ''),
        maxConnections: msg.maxConnections || 5,
        host: msg.host || `${this.localIp}:${this.port}`,
        receivers: [],
      };
      const response: SignalingMessage = {
        type: 'created',
        code: this.room.code,
        senderToken: this.room.senderToken,
        maxConnections: this.room.maxConnections,
        receiverUrl: `http://${this.localIp}:${this.port}/receiver?code=${this.room.code}`,
        qrDataUrl: null as any,  // will be generated by QrService later
      };
      this.senderHandlers.forEach((h) => h(response));
      return;
    }
    if (msg.type === 'close-room') {
      this.room = null;
      this.receivers.forEach((r) => {
        try { r.ws.send(JSON.stringify({ type: 'peer-disconnected' })); } catch (_) {}
        try { r.ws.close(4001, 'room_closed'); } catch (_) {}
      });
      this.receivers.clear();
      this.senderHandlers.forEach((h) => h({ type: 'room-closed' } as SignalingMessage));
      return;
    }
    if (msg.type === 'resume-sender') {
      if (!this.room || this.room.code !== msg.code || this.room.senderToken !== msg.senderToken) {
        this.senderHandlers.forEach((h) => h({ type: 'error', message: '无法恢复房间', code: 'resume_failed' } as SignalingMessage));
        return;
      }
      const response: SignalingMessage = {
        type: 'sender-resumed',
        code: this.room.code,
        receivers: this.room.receivers,
        receiverUrl: `http://${this.localIp}:${this.port}/receiver?code=${this.room.code}`,
      };
      this.senderHandlers.forEach((h) => h(response));
      return;
    }
    // Route message to specific receiver if targetReceiverId is set
    if (msg.targetReceiverId) {
      const receiver = this.receivers.get(msg.targetReceiverId);
      if (receiver && receiver.ws.readyState === WebSocket.OPEN) {
        receiver.ws.send(JSON.stringify(msg));
      }
      return;
    }
    // Broadcast to all receivers (e.g., sender-disconnected, etc.)
    this.receivers.forEach((receiver) => {
      if (receiver.ws.readyState === WebSocket.OPEN) {
        receiver.ws.send(JSON.stringify(msg));
      }
    });
  }

  onSenderMessage(handler: (msg: SignalingMessage) => void): void {
    this.senderHandlers.add(handler);
  }

  offSenderMessage(handler: (msg: SignalingMessage) => void): void {
    this.senderHandlers.delete(handler);
  }

  private listen(preferredPort: number): Promise<number> {
    return new Promise((resolve, reject) => {
      this.httpServer = this.appExpress.listen(preferredPort, '0.0.0.0', () => {
        const addr = this.httpServer?.address();
        this.port = typeof addr === 'object' && addr ? addr.port : preferredPort;
        console.log(`[LocalSignaling] Listening on port ${this.port}`);
        resolve(this.port);
      });
      this.httpServer.on('error', (err: any) => {
        if (err.code === 'EADDRINUSE') {
          console.warn(`[LocalSignaling] Port ${preferredPort} in use, trying random port...`);
          try { this.httpServer?.close(); } catch (_) {}
          const fallbackServer = this.appExpress.listen(0, '0.0.0.0', () => {
            this.httpServer = fallbackServer;
            const addr = this.httpServer?.address();
            this.port = typeof addr === 'object' && addr ? addr.port : 0;
            console.log(`[LocalSignaling] Fallback listening on port ${this.port}`);
            resolve(this.port);
          });
          fallbackServer.on('error', (fallbackErr: any) => {
            console.error('[LocalSignaling] Fallback listen also failed:', fallbackErr.message);
            this.port = 0;
            resolve(0);
          });
        } else {
          console.error('[LocalSignaling] Listen error:', err.message);
          reject(err);
        }
      });
    });
  }

  private setupWebSocket(): void {
    this.wss = new WebSocketServer({ server: this.httpServer! });

    this.wss.on('connection', (ws, req) => {
      const url = new URL(req.url || '/', `http://${req.headers.host}`);
      const role = url.searchParams.get('role') || 'receiver';

      if (role === 'sender') {
        this.handleSenderConnection(ws);
      } else {
        this.handleReceiverConnection(ws);
      }
    });
  }

  private handleSenderConnection(ws: WebSocket): void {
    this.senderWs = ws;

    ws.on('message', (data: WebSocket.Data) => {
      try {
        const msg = JSON.parse(data.toString()) as SignalingMessage;
        if (msg.type === 'create') {
          this.room = {
            code: this.generateRoomCode(),
            senderToken: uuidv4().replace(/-/g, ''),
            maxConnections: msg.maxConnections || 5,
            host: `${this.localIp}:${this.port}`,
            receivers: [],
          };
          ws.send(JSON.stringify({
            type: 'created',
            code: this.room.code,
            senderToken: this.room.senderToken,
            maxConnections: this.room.maxConnections,
            receiverUrl: `http://${this.localIp}:${this.port}/receiver?code=${this.room.code}`,
          }));
          return;
        }
        if (msg.type === 'close-room') {
          this.room = null;
          this.receivers.clear();
          return;
        }
        this.senderHandlers.forEach((h) => h(msg));
      } catch (e) {
        console.error('本地 sender 消息解析失败:', e);
      }
    });

    ws.on('close', () => {
      this.senderWs = null;
    });
  }

  private handleReceiverConnection(ws: WebSocket): void {
    let receiverId = '';  // track which receiver this WS belongs to
    ws.on('message', (data: WebSocket.Data) => {
      try {
        const msg = JSON.parse(data.toString()) as SignalingMessage;
        if (msg.type === 'join') {
          if (!this.room || this.room.code !== msg.code) {
            ws.send(JSON.stringify({ type: 'error', code: 'room_not_found' }));
            return;
          }
          receiverId = `dev-lan-${uuidv4().replace(/-/g, '').slice(0, 12)}`;
          const joinToken = uuidv4().replace(/-/g, '');
          const receiver: LocalReceiver = {
            receiverId,
            joinToken,
            clientId: msg.clientId || `bc-${uuidv4().replace(/-/g, '').slice(0, 16)}`,
            nickname: msg.nickname || '听众',
            ws,
          };
          this.receivers.set(receiverId, receiver);
          this.room.receivers.push({
            receiverId,
            nickname: receiver.nickname,
            connections: 1,
          });

          ws.send(JSON.stringify({
            type: 'joined',
            receiverId,
            joinToken,
            nickname: receiver.nickname,
            resumed: false,
          }));

          // Notify sender via app (no senderWs in Electron — main process IS sender)
          const peerReadyMsg: SignalingMessage = {
            type: 'peer-ready',
            receiverId,
            nickname: receiver.nickname,
            connections: 1,
            netType: msg.netType || 'wifi',
          };
          this.senderHandlers.forEach((h) => h(peerReadyMsg));

          this.app.handleReceiverJoined({
            receiverId,
            nickname: receiver.nickname,
            connections: 1,
            netType: msg.netType || 'wifi',
          });
          return;
        }

        // Route message: if targetReceiverId → forward to that receiver
        // Otherwise → forward to sender (main process, via app)
        if (msg.targetReceiverId) {
          const receiver = this.receivers.get(msg.targetReceiverId);
          if (receiver && receiver.ws.readyState === WebSocket.OPEN) {
            receiver.ws.send(JSON.stringify(msg));
          }
        } else {
          // Forward to sender: use app.handleReceiverSignaling (main process IS sender)
          this.app.handleReceiverSignaling(receiverId || '', msg);
        }
      } catch (e) {
        console.error('本地 receiver 消息解析失败:', e);
      }
    });

    ws.on('close', () => {
      this.receivers.forEach((receiver, id) => {
        if (receiver.ws === ws) {
          this.receivers.delete(id);
          const leftMsg: SignalingMessage = { type: 'peer-left', receiverId: id };
          this.senderHandlers.forEach((h) => h(leftMsg));
          this.app.handleReceiverLeft(id);
        }
      });
    });
  }

  private generateRoomCode(): string {
    const chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
    let code = '';
    for (let i = 0; i < 5; i++) {
      code += chars.charAt(Math.floor(Math.random() * chars.length));
    }
    return code;
  }

  private getLocalIpInternal(): string {
    const candidates = this.collectCandidates();
    if (candidates.length === 0) return '127.0.0.1';
    console.log('[LocalSignaling] Available IPs:', candidates.map(c => `${c.address} (${c.name})`).join(', '));
    console.log('[LocalSignaling] Selected IP:', candidates[0].address);
    return candidates[0].address;
  }
}
